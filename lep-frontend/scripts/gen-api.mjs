#!/usr/bin/env node
// Generates the typed API client surface from the backend's own OpenAPI document.
//
//   openapi/openapi.json          the server's schema (copy of lep-backend/openapi.json, or
//                                 fetched with LEP_OPENAPI_URL=http://host:8000/openapi.json)
//   src/api/schema.generated.ts   openapi-typescript output (paths, components)
//   src/api/paths.generated.ts    the list of paths the server offers, used at runtime to know
//                                 which capabilities exist (DECISIONS F7 / "capabilities")
//
// Never hand-write an endpoint path: add it to the server, re-export its schema, re-run this.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const schemaPath = join(root, 'openapi/openapi.json');

if (process.env.LEP_OPENAPI_URL) {
  const res = await fetch(process.env.LEP_OPENAPI_URL);
  if (!res.ok) throw new Error(`could not fetch ${process.env.LEP_OPENAPI_URL}: ${res.status}`);
  writeFileSync(schemaPath, JSON.stringify(await res.json(), null, 2) + '\n');
  console.log(`api: refreshed openapi/openapi.json from ${process.env.LEP_OPENAPI_URL}`);
}

const doc = JSON.parse(readFileSync(schemaPath, 'utf8'));
const ast = await openapiTS(doc, { exportType: true, alphabetize: true });
const banner =
  '// GENERATED by scripts/gen-api.mjs from openapi/openapi.json. Do not edit by hand.\n\n';
writeFileSync(join(root, 'src/api/schema.generated.ts'), banner + astToString(ast));

const operations = [];
for (const [path, item] of Object.entries(doc.paths)) {
  for (const method of Object.keys(item)) {
    if (['get', 'post', 'put', 'patch', 'delete'].includes(method)) {
      operations.push(`${method.toUpperCase()} ${path}`);
    }
  }
}
operations.sort();
writeFileSync(
  join(root, 'src/api/paths.generated.ts'),
  banner +
    `/** Every operation the server's schema offers, as "METHOD /path". */\n` +
    `export const serverOperations = ${JSON.stringify(operations, null, 2)} as const;\n\n` +
    `export type ServerOperation = (typeof serverOperations)[number];\n\n` +
    `export const apiVersion = ${JSON.stringify(doc.info?.version ?? 'unknown')};\n`,
);
console.log(`api: ${operations.length} operations from ${doc.info?.title} ${doc.info?.version}`);
